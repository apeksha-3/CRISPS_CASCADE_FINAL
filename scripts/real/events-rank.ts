// scripts/real/events-rank.ts
// Phase 8 step C2. Rank the NWS candidate events by how hard it rained (IEM 1-minute data, heaviest 60 minutes,
// max over the 3 stations), then check DOT, EMS and 311 coverage for the heaviest ones. Selection happens here,
// from rain and coverage only: never from what the engine does with an event.
//
// Rule: an event is usable if, on its first local day and the next, DOT has >= 20,000 rows, EMS >= 3,000 rows and
// 311 (all types) >= 3,000 rows. Usable events are taken heaviest first until there are NEW_EVENTS of them.
// Run: npx tsx scripts/real/events-rank.ts

import { readFileSync, writeFileSync } from "node:fs";
import { parseCsv } from "../../real/csv";
import { type ManifestEntry, saveRaw } from "../../real/manifest";
import { cachedGet } from "../../real/net";
import type { FloodEvent } from "../../real/nws";
import { fetchAggregate } from "../../real/soda";
import { addDays, localIsoToUtcMs, utcMsToIemZ, utcStringToMs } from "../../real/tz";

const NEW_EVENTS = 8;
const cand = JSON.parse(readFileSync("real/candidates.json", "utf8")) as { events: FloodEvent[] };
const entries: ManifestEntry[] = JSON.parse(readFileSync("data/real/manifest-nws.json", "utf8"));

interface Ranked extends FloodEvent {
  day: string;
  peak60_mm?: number;
  peak60_start_local?: string;
  coverage?: { dot: number[]; ems: number[]; c311: number[]; ok: boolean };
}

async function peak60(day: string): Promise<{ mm: number; start: number } | undefined> {
  const sts = utcMsToIemZ(localIsoToUtcMs(`${day}T00:00:00`));
  const ets = utcMsToIemZ(localIsoToUtcMs(`${addDays(day, 2)}T00:00:00`));
  const url = `https://mesonet.agron.iastate.edu/cgi-bin/request/asos1min.py?station=NYC&station=JFK&station=LGA&vars=precip&sts=${encodeURIComponent(sts)}&ets=${encodeURIComponent(ets)}&sample=1min&what=download&delim=comma&tz=UTC`;
  const r = await cachedGet(`iem-rank-${day}`, url, { timeoutMs: 120_000 });
  if (r.status !== 200) throw new Error(`iem ${day}: ${r.status}`);
  const rows = parseCsv(r.body);
  entries.push(saveRaw(`iem-rank__${day}.csv`, r.body, { dataset: "iem-rank", window: day, query: url, rows: rows.length }));
  let best: { mm: number; start: number } | undefined;
  for (const st of ["NYC", "JFK", "LGA"]) {
    const per = new Map<number, number>();
    for (const x of rows) if (x.station === st && x.precip !== "" && x.precip !== "M" && Number.isFinite(Number(x.precip))) per.set(utcStringToMs(x["valid(UTC)"]), Number(x.precip) * 25.4);
    for (const t0 of [...per.keys()].sort((a, b) => a - b)) {
      let sum = 0;
      let n = 0;
      for (let k = 0; k < 60; k++) {
        const v = per.get(t0 + k * 60_000);
        if (v !== undefined) {
          sum += v;
          n++;
        }
      }
      if (n >= 48 && (!best || sum > best.mm)) best = { mm: sum, start: t0 };
    }
  }
  return best;
}

const ranked: Ranked[] = [];
for (const e of cand.events) {
  const day = e.first_local.slice(0, 10);
  const p = await peak60(day);
  ranked.push({ ...e, day, peak60_mm: p ? Math.round(p.mm * 10) / 10 : undefined, peak60_start_local: p ? new Date(p.start).toISOString() : undefined });
}
ranked.sort((a, b) => (b.peak60_mm ?? -1) - (a.peak60_mm ?? -1));

const count = async (prefix: string, dataset: string, field: string, day: string, where = "") =>
  Number((await fetchAggregate(prefix, dataset, { $select: "count(*) as n", $where: `${field} >= '${day}T00:00:00' AND ${field} < '${addDays(day, 1)}T00:00:00'${where}` }))[0].n);

let usable = 0;
console.log("rank event           first NYC warning     peak 60-min rain  usable (DOT / EMS / 311 rows on day 1 and day 2)");
for (const [i, e] of ranked.entries()) {
  if (i >= 30 && usable >= NEW_EVENTS + 2) break;
  const days = [e.day, addDays(e.day, 1)];
  const dot = await Promise.all(days.map((d) => count(`cov-dot-${d}`, "i4gi-tjb9", "data_as_of", d)));
  const ems = await Promise.all(days.map((d) => count(`cov-ems-${d}`, "76xm-jjuj", "incident_datetime", d)));
  const c311 = await Promise.all(days.map((d) => count(`cov-311-${d}`, "erm2-nwe9", "created_date", d)));
  const ok = dot.every((x) => x >= 20000) && ems.every((x) => x >= 3000) && c311.every((x) => x >= 3000);
  e.coverage = { dot, ems, c311, ok };
  if (ok) usable++;
  console.log(`${String(i + 1).padStart(3)}  ${e.id.padEnd(15)} ${e.first_local.padEnd(19)}   ${String(e.peak60_mm ?? "-").padStart(8)} mm        ${ok ? "yes" : "NO "}  ${dot.join("/")} | ${ems.join("/")} | ${c311.join("/")}${e.emergency_nyc ? "  FFE" : ""}`);
}
const chosen = ranked.filter((e) => e.coverage?.ok).slice(0, NEW_EVENTS + 2).map((e) => e.id);
writeFileSync("real/ranking.json", JSON.stringify({ note: "Generated by scripts/real/events-rank.ts from real/candidates.json. peak60_mm = heaviest 60 minutes of rain, max over KNYC/KJFK/KLGA. coverage = row counts on the event's first local day and the next.", ranked_by_rain: ranked.slice(0, 30), usable_in_rain_order: chosen }, null, 1) + "\n");
writeFileSync("data/real/manifest-nws.json", JSON.stringify(entries));
console.log(`\nusable, heaviest first: ${chosen.join(" ")}`);
