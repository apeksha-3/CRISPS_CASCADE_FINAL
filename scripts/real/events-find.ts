// scripts/real/events-find.ts
// Phase 8 step C1. Every NWS Flash Flood Warning / Emergency that named a New York City county, 2019 to now,
// from the IEM archive of NWS text products. Prints the candidate list and writes real/candidates.json.
// Run: npx tsx scripts/real/events-find.ts

import { writeFileSync } from "node:fs";
import { saveRaw, type ManifestEntry } from "../../real/manifest";
import { cachedGet } from "../../real/net";
import { groupEvents, parseFfwBundle, type Ffw } from "../../real/nws";

const all: Ffw[] = [];
const entries: ManifestEntry[] = [];
const end = new Date().toISOString().slice(0, 10);
for (let y = 2019; y <= new Date().getUTCFullYear(); y++) {
  for (const [a, b] of [[`${y}-01-01`, `${y}-07-01`], [`${y}-07-01`, `${y + 1}-01-01`]]) {
    if (a > end) continue;
    const url = `https://mesonet.agron.iastate.edu/cgi-bin/afos/retrieve.py?pil=FFWOKX&limit=9999&sdate=${a}T00:00Z&edate=${b}T00:00Z&fmt=text`;
    const r = await cachedGet(`nws-ffw-${a}`, url, { timeoutMs: 120_000 });
    if (r.status !== 200) throw new Error(`${url}: ${r.status === 0 ? r.body : r.status}`);
    const found = parseFfwBundle(r.body);
    entries.push(saveRaw(`nws-ffw-archive-${a}.txt`, r.body, { dataset: "nws-ffw-archive", window: `${a}..${b}`, query: url, rows: found.length }));
    all.push(...found);
  }
}
const events = groupEvents(all);
console.log(`${all.length} OKX flash flood warning products, ${events.length} events that named a NYC county, ${events.filter((e) => e.emergency_nyc).length} with a flash flood EMERGENCY for NYC`);
console.log("event            first NYC warning (local)  last              products new  EMERG  boroughs");
for (const e of events) console.log(`${e.id.padEnd(16)} ${e.first_local.padEnd(19)}   ${e.last_local.slice(5, 16).padEnd(16)}  ${String(e.products).padStart(7)} ${String(e.new_products).padStart(4)}  ${e.emergency_nyc ? "YES  " : "no   "}  ${e.boroughs.join(",")}`);
writeFileSync("real/candidates.json", JSON.stringify({ note: "Generated by scripts/real/events-find.ts from the IEM archive of NWS FFW products (OKX). An event = NYC-county warning products with gaps under 8 hours.", events }, null, 1) + "\n");
writeFileSync("data/real/manifest-nws.json", JSON.stringify(entries));
