// eval/tune.ts
// `npm run tune -- --split dev`  (dev ONLY: refuses any other split)
// One-time calibration step, never run during eval:
//   1. likelihood tables: 3 passes of coordinate search on dev Brier (engine/tune.ts),
//      each pass starting from a fresh full engine run that records the replay traces.
//      Tuning set = the dev split + a dev LOOKALIKE POOL (40 rain-only, 40 storm-calls,
//      40 flu-cluster days, seeds 3500-3739, all in the dev range). The dev split has only
//      12 / 10 / 9 of those; with so few, the false-alarm guard could not see that a
//      change made rain days alert more often (first test run: rain-only FA 33%).
//   2. forecast lags: mean / sd of the true stage-to-stage lags in dev cascades
// Writes config/likelihoods.ts (dev-tuned tables) and config/lags.ts (measured lags).
// The hand-set originals stay in config/likelihoods-handset.ts and config/causal-graph.ts.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CAUSAL_ORDER, HANDSET_LAGS } from "../config/causal-graph";
import { HANDSET_TABLES, type LikelihoodTables } from "../config/likelihoods-handset";
import { forwardFilter, silenceLL, unitRow, zeroRow } from "../engine/filter";
import { type EpisodeTrace, lagStats, NO_HARM_TOLERANCE, perType, replayBrier, replayObjective, replayStats, searchPass, type TickTrace, tableRows, typeBalanced } from "../engine/tune";
import { type EventKind, HYPOTHESES } from "../engine/types";
import { groupOf, loadSplit } from "../sim/dataset";
import { generateEpisode } from "../sim/episode";
import type { Episode } from "../sim/truth";
import { enginePolicy, learningFor } from "./baselines";
import { groupBy, summarize } from "./report";
import { type EpisodeResult, eventLabels, evalOrder, runEpisode } from "./run";

const PASSES = 3;
const POOL_SIZE = 40; // per lookalike type

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

// A full engine run over dev (the same set-up as `npm run eval -- --split dev --policy engine`),
// recording what replay needs at every tick.
interface FullRun {
  brier: number; // plain mean over episodes (the eval's number)
  objective: number; // type-balanced (what the search minimizes)
  traces: EpisodeTrace[];
  results: EpisodeResult[];
}

function fullRun(episodes: Episode[], tables: LikelihoodTables): FullRun {
  const traces: EpisodeTrace[] = [];
  let ticks: TickTrace[] = [];
  let mirror = new Map<string, { key: string; scale: number }>(); // what each unit currently adds
  const recordingFilter: typeof forwardFilter = (prior, updates, statuses, config, extra = []) => {
    const fr = forwardFilter(prior, updates, statuses, config, extra);
    const coef: Record<string, number> = {};
    for (const { unit } of updates) {
      const now = unitRow(unit, config!.tables);
      const before = mirror.get(unit.unit_id);
      if (now) coef[now.key] = (coef[now.key] ?? 0) + now.scale;
      if (before) coef[before.key] = (coef[before.key] ?? 0) - before.scale;
      if (now) mirror.set(unit.unit_id, { key: now.key, scale: now.scale });
      else mirror.delete(unit.unit_id);
    }
    for (const k of Object.keys(coef)) if (Math.abs(coef[k]) < 1e-12) delete coef[k];
    const fixed = zeroRow();
    for (const row of extra) for (const h of HYPOTHESES) fixed[h] += row[h];
    fixed.SENSOR_FAILURE += silenceLL(statuses, config!.knobs);
    ticks.push({ coef, fixed, coverage: fr.coverage });
    return fr;
  };
  const policy = enginePolicy("tune", learningFor("dev"), tables, () => {
    ticks = [];
    mirror = new Map();
    return { filter: recordingFilter };
  });
  const results: EpisodeResult[] = [];
  for (const ep of episodes) {
    const { result, records } = runEpisode(policy, ep);
    if (records.some((r) => r.fallback)) throw new Error(`fallback tick in ${ep.episode_id}: replay would be wrong`);
    traces.push({ episode_id: ep.episode_id, group: groupOf(ep), truth: ep.truth.hypothesis, prior: result.prior, ticks });
    results.push(result);
    policy.afterEpisode?.(ep.truth.hypothesis, eventLabels(ep));
  }
  return { brier: summarize(results).brier, objective: typeBalanced(results), traces, results };
}

const n2 = (x: number) => {
  const v = Math.round(x * 100) / 100;
  return Object.is(v, -0) ? "0" : String(v);
};
const rowSrc = (r: Record<string, number>) => `row(${HYPOTHESES.map((h) => n2(r[h])).join(", ")})`;

function renderLikelihoods(t: LikelihoodTables, header: string[]): string {
  const L = [
    "// config/likelihoods.ts",
    "// DEV-TUNED likelihood tables: the engine's defaults since Phase 4.",
    "// GENERATED by `npm run tune -- --split dev` (eval/tune.ts). Do not hand-edit:",
    "// change config/likelihoods-handset.ts (the hand-set originals, which also hold",
    "// the types, the `upstream` rules and the severity gate) and re-run the tuner.",
    "// Columns: NOISE, SENSOR_FAILURE, ISOLATED, CASCADE (log-likelihoods, nats). NOISE is",
    "// the fixed reference column; the tuner moves the other three by +/-0.1 or 0.2 at a time.",
    ...header.map((h) => `// ${h}`),
    "",
    'import { HANDSET_LIKELIHOODS as H, type LikelihoodTables, row } from "./likelihoods-handset";',
    'export type { KindLikelihood, LikelihoodTables, LLRow, Upstream } from "./likelihoods-handset";',
    'export { SEVERITY_GATE } from "./likelihoods-handset";',
    "",
    "export const TUNED_TABLES: LikelihoodTables = {",
    "  kinds: {",
  ];
  for (const [kind, k] of Object.entries(t.kinds)) {
    if (!k) continue;
    const parts = [];
    if (k.upstream) parts.push(`upstream: H.${kind}!.upstream`);
    if (k.chained) parts.push(`chained: ${rowSrc(k.chained)}`);
    parts.push(`alone: ${rowSrc(k.alone)}`);
    L.push(`    ${kind}: { ${parts.join(", ")} },`);
  }
  L.push("  },", `  low: ${rowSrc(t.low)},`, `  gateway: ${rowSrc(t.gateway)},`, `  rumor: ${rowSrc(t.rumor)},`, "};", "");
  L.push("// The names the rest of the engine imports.");
  L.push("export const LIKELIHOODS = TUNED_TABLES.kinds;");
  L.push("export const LOW_SEVERITY = TUNED_TABLES.low;");
  L.push("export const GATEWAY_CORRELATED = TUNED_TABLES.gateway;");
  L.push("export const RUMOR_CAPPED = TUNED_TABLES.rumor;");
  return L.join("\n") + "\n";
}

function renderLags(stats: ReturnType<typeof lagStats>, nEpisodes: number): string {
  const L = [
    "// config/lags.ts",
    "// Forecast lags MEASURED on dev: for each edge of the causal chain, the time from the",
    "// first start of the upstream stage to the first start of the downstream stage,",
    `// over the ${nEpisodes} dev episodes whose truth is CASCADE (mean and sd, seconds; n = how many).`,
    "// GENERATED by `npm run tune -- --split dev` (eval/tune.ts). Honest note: dev comes from",
    "// our own simulator, so these mostly re-discover its lags; with real data they would update.",
    "// Keyed by the downstream stage. Edges missing here use HANDSET_LAGS (config/causal-graph.ts).",
    "",
    'import type { EventKind } from "../engine/types";',
    "",
    "export const LEARNED_LAGS: Partial<Record<EventKind, { mean: number; sd: number; n: number }>> = {",
  ];
  for (const [k, v] of Object.entries(stats)) L.push(`  ${k}: { mean: ${v!.mean}, sd: ${v!.sd}, n: ${v!.n} },`);
  L.push("};");
  return L.join("\n") + "\n";
}

function main(): void {
  const split = arg("split") ?? "dev";
  if (split !== "dev") throw new Error(`refusing to tune on "${split}": tuning uses the dev split only`);
  const pool: Episode[] = [];
  for (let i = 0; i < POOL_SIZE; i++) {
    pool.push(generateEpisode("rain_only", 3500 + i), generateEpisode("storm_calls", 3600 + i), generateEpisode("flu_cluster", 3700 + i));
  }
  const devSplit = loadSplit("dev");
  const episodes = evalOrder("dev", [...devSplit, ...pool]);
  console.log(`Tuning on dev: the dev split (${devSplit.length}) + a dev lookalike pool (${pool.length}: rain-only, storm-calls, flu-cluster, seeds 3500-3739) = ${episodes.length} episodes,`);
  console.log("played in one fixed shuffled order with trust learning (as in --policy engine).");
  console.log("");

  // ---- A. likelihood tables ----
  const handset = fullRun(episodes, HANDSET_TABLES);
  const check = replayBrier(handset.traces, HANDSET_TABLES);
  console.log(`hand-set tables: full-run dev Brier ${handset.brier.toFixed(4)}   replay of the same run ${check.toFixed(4)} (must match)`);
  if (Math.abs(check - handset.brier) > 1e-9) throw new Error("replay does not reproduce the full run");
  console.log(`objective = Brier per episode type, averaged over the ${new Set(handset.traces.map((t) => t.group)).size} types: hand-set ${handset.objective.toFixed(4)} (replay ${replayObjective(handset.traces, HANDSET_TABLES).toFixed(4)})`);
  const handTypes = perType(handset.results);
  const limits = new Map([...handTypes].map(([g, b]) => [g, b + NO_HARM_TOLERANCE]));
  const handAlerts = replayStats(handset.traces, HANDSET_TABLES).benignAlerts;
  const realFA = handset.results.filter((r) => (r.hypothesis === "NOISE" || r.hypothesis === "SENSOR_FAILURE") && r.any_alert).length;
  console.log(`do-no-harm rules: no episode type may end more than ${NO_HARM_TOLERANCE} Brier worse than hand-set,`);
  console.log(`  and no more than ${handAlerts} benign episodes may "would alert" in replay (hand-set's count; the real hand-set run alerted on ${realFA})`);
  let tables = HANDSET_TABLES;
  let current = handset;
  const allChanges: { key: string; h: string; from: number; to: number }[] = [];
  for (let pass = 1; pass <= PASSES; pass++) {
    const p = searchPass(current.traces, tables, limits, handAlerts);
    const next = fullRun(episodes, p.tables);
    console.log(
      `pass ${pass}: ${String(p.changes.length).padStart(2)} cells changed, objective replay ${p.objective.toFixed(4)} / full run ${next.objective.toFixed(4)} (was ${current.objective.toFixed(4)}); plain Brier ${next.brier.toFixed(4)} (was ${current.brier.toFixed(4)})`,
    );
    if (next.objective >= current.objective - 1e-6) {
      console.log(`pass ${pass} did not lower the full-run objective: rejected, stopping.`);
      break;
    }
    for (const c of p.changes) allChanges.push({ key: c.cell.key, h: c.cell.h, from: c.from, to: c.to });
    tables = p.tables;
    current = next;
  }
  // net change per cell
  const net = new Map<string, { key: string; h: string; from: number; to: number }>();
  for (const c of allChanges) {
    const id = `${c.key}|${c.h}`;
    net.set(id, { ...c, from: net.get(id)?.from ?? c.from });
  }
  const changed = [...net.values()].filter((c) => Math.abs(c.to - c.from) > 1e-9);
  console.log("");
  console.log(`tuning-set Brier: hand-set ${handset.brier.toFixed(4)} -> tuned ${current.brier.toFixed(4)}  (${(current.brier - handset.brier).toFixed(4)});  type-balanced ${handset.objective.toFixed(4)} -> ${current.objective.toFixed(4)}`);
  const fa = (rs: EpisodeResult[]) => rs.filter((r) => (r.hypothesis === "NOISE" || r.hypothesis === "SENSOR_FAILURE") && r.any_alert).length;
  console.log(`tuning-set benign episodes that reached ALERT+ (full runs): hand-set ${fa(handset.results)} -> tuned ${fa(current.results)}`);
  console.log(`${changed.length} of ${Object.keys(tableRows(HANDSET_TABLES)).length * 3} tunable cells changed (net, in nats):`);
  for (const c of changed) console.log(`  ${c.key.padEnd(36)} ${c.h.padEnd(18)} ${n2(c.from).padStart(6)} -> ${n2(c.to).padStart(6)}`);
  console.log("");
  console.log("tuning-set Brier per group (full runs):");
  const gh = new Map(groupBy(handset.results).map(([g, rs]) => [g, summarize(rs).brier]));
  for (const [g, rs] of groupBy(current.results)) {
    const t = summarize(rs).brier;
    console.log(`  ${g.padEnd(26)} hand-set ${gh.get(g)!.toFixed(3)}   tuned ${t.toFixed(3)}${t > gh.get(g)! + NO_HARM_TOLERANCE ? "   (above the do-no-harm limit in the full run)" : ""}`);
  }

  // ---- B. lags ----
  const cascades = episodes.filter((e) => e.truth.hypothesis === "CASCADING_CRISIS");
  const samples: { to: EventKind; lag: number }[] = [];
  for (const ep of cascades) {
    const st = ep.truth.stage_times;
    for (let i = 1; i < CAUSAL_ORDER.length; i++) {
      const a = st[CAUSAL_ORDER[i - 1]];
      const b = st[CAUSAL_ORDER[i]];
      if (a !== undefined && b !== undefined) samples.push({ to: CAUSAL_ORDER[i], lag: b - a });
    }
  }
  const lags = lagStats(samples);
  console.log("");
  console.log(`forecast lags from ${cascades.length} dev cascade episodes (seconds):`);
  for (let i = 1; i < CAUSAL_ORDER.length; i++) {
    const k = CAUSAL_ORDER[i];
    const h = HANDSET_LAGS[k]!;
    const l = lags[k];
    console.log(`  ${CAUSAL_ORDER[i - 1].padEnd(26)} -> ${k.padEnd(26)} hand-set ${h.mean} +/- ${h.sd}   measured ${l ? `${l.mean} +/- ${l.sd} (n ${l.n})` : "(too few, hand-set kept)"}`);
  }

  const header = [
    `Objective: dev Brier per episode type, averaged over types, with do-no-harm rules (no type`,
    `more than ${NO_HARM_TOLERANCE} worse than hand-set, no extra benign "would alert" episodes). engine/tune.ts explains why.`,
    `Tuning set = dev split + dev lookalike pool (${episodes.length} episodes), full engine runs with trust learning:`,
    `Brier hand-set ${handset.brier.toFixed(4)} -> tuned ${current.brier.toFixed(4)}; type-balanced ${handset.objective.toFixed(4)} -> ${current.objective.toFixed(4)}.`,
    "The eval's dev split alone: see docs/phase-reports/phase-4.md.",
    `${changed.length} cells changed; the hand-set value of each is in config/likelihoods-handset.ts.`,
  ];
  writeFileSync(join(process.cwd(), "config", "likelihoods.ts"), renderLikelihoods(tables, header));
  writeFileSync(join(process.cwd(), "config", "lags.ts"), renderLags(lags, cascades.length));
  console.log("");
  console.log("wrote config/likelihoods.ts and config/lags.ts");
}

main();
